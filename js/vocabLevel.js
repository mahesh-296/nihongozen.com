// ═══════════════════════════════════════════════════════════════════════════════
// SELF-PATCHING: Override chapter button rendering for N5 to use Dai-labels
// and wire SRS Review pills to launch level-specific vocabulary revision.
//
// Runs after DOM is ready (DOMContentLoaded or immediately if DOM exists).
// Patches:
//   1. Chapter buttons for N5 → show 挨拶 / Dai-ikka … Dai-niju-goka labels
//      styled identically to the existing chapter buttons.
//   2. SRS Review by Level pills → each pill, on click, switches the active
//      level tab AND scrolls the chapter area into view, launching revision
//      for the first chapter of that level.
// ═══════════════════════════════════════════════════════════════════════════════

(function applyNZPatch() {
  'use strict';

  /* ── Helpers ──────────────────────────────────────────────────────────── */

  /** Find a module-scoped variable on the page by scanning known module containers. */
  function waitForEl(selector, timeout, cb) {
    const start = Date.now();
    const iv = setInterval(() => {
      const el = document.querySelector(selector);
      if (el) { clearInterval(iv); cb(el); }
      else if (Date.now() - start > timeout) { clearInterval(iv); }
    }, 120);
  }

  /* ── 1. Chapter Button Labels for N5 ─────────────────────────────────── */

  /**
   * Observes #vocab-ch-btns and rewrites button text whenever
   * the active level is N5.
   */
  function patchN5ChapterButtons() {
    const container = document.getElementById('vocab-ch-btns');
    if (!container) return;

    const labels = window.NZN5ChapterLabels || [];

    function rewrite() {
      // Only rewrite when the N5 level tab is active
      const activeTab = document.querySelector('.nz-lvl-tab.active, [data-level].active');
      const currentLevel = activeTab ? activeTab.dataset.level : null;

      // Try reading activeLevel from the rendered book label badge
      const bookBadge = container.querySelector('span[style*="background"]');
      const bookText  = bookBadge ? bookBadge.textContent : '';
      const isN5      = bookText.includes('Minna no Nihongo I') ||
                        (currentLevel === 'N5') ||
                        (!currentLevel && bookText === '');

      if (!isN5) return; // only patch N5

      const buttons = container.querySelectorAll('.vocab-ch-btn');
      buttons.forEach((btn, i) => {
        const meta = labels[i];
        if (!meta) return;
        if (i === 0) {
          // Greetings button: show Japanese label 挨拶
          btn.textContent = meta.jaLabel; // 挨拶
          btn.title = 'Greetings — Preliminary Lesson';
          // Give it a slightly wider min-width so the kanji is readable
          btn.style.minWidth = '52px';
          btn.style.fontFamily = 'inherit';
        } else {
          btn.textContent = meta.daiLabel; // Dai-ikka … Dai-niju-goka
          btn.title = meta.jaLabel + ': ' + (btn.title || '');
        }
      });
    }

    // Observe mutations to catch re-renders
    const obs = new MutationObserver(rewrite);
    obs.observe(container, { childList: true, subtree: true });
    rewrite(); // run immediately in case already rendered
  }

  /* ── 2. SRS Review Pills: Level-Specific Revision Launch ─────────────── */

  /**
   * Replaces the plain SRS pill buttons with enhanced ones that:
   *   a. Switch the active level tab to the clicked level.
   *   b. Reset chapter to 0 (first chapter of that level).
   *   c. Scroll the chapter buttons into view for a seamless UX.
   *   d. Briefly highlight the active level tab.
   *
   * The pills stay always-visible by being sticky at the top of the
   * vocabulary study section.
   */
  function enhanceSRSPills() {
    const srsWrap = document.getElementById('vocab-srs-pills');
    if (!srsWrap) return;

    const LEVEL_COLORS = {
      N5: '#22c55e', N4: '#06b6d4', N3: '#eab308', N2: '#a855f7', N1: '#ef4444'
    };
    const LEVELS = ['N5', 'N4', 'N3', 'N2', 'N1'];

    srsWrap.innerHTML = LEVELS.map(lvl => `
      <button
        class="nz-srs-pill nz-srs-pill-${lvl}"
        data-level="${lvl}"
        style="
          padding: 6px 16px;
          border-radius: 8px;
          font-size: 13px;
          font-weight: 700;
          background: transparent;
          border: 1.5px solid ${LEVEL_COLORS[lvl]};
          color: ${LEVEL_COLORS[lvl]};
          cursor: pointer;
          font-family: inherit;
          transition: background 0.15s, transform 0.1s;
          letter-spacing: 0.03em;
        "
        title="Launch SRS Review for ${lvl}"
      >${lvl}</button>
    `).join('');

    srsWrap.querySelectorAll('.nz-srs-pill').forEach(btn => {
      const lvl = btn.dataset.level;
      const color = LEVEL_COLORS[lvl];

      btn.addEventListener('mouseenter', () => {
        btn.style.background = color + '22';
        btn.style.transform  = 'scale(1.04)';
      });
      btn.addEventListener('mouseleave', () => {
        btn.style.background = 'transparent';
        btn.style.transform  = 'scale(1)';
      });

      btn.addEventListener('click', () => {
        // 1. Find and click the matching level tab
        const levelTabs = document.querySelectorAll('.nz-lvl-tab[data-level]');
        levelTabs.forEach(tab => {
          if (tab.dataset.level === lvl) {
            tab.click();
          }
        });

        // 2. Scroll the chapter button area into view after a short wait
        //    so the re-render has time to complete.
        setTimeout(() => {
          const chBtns = document.getElementById('vocab-ch-btns');
          if (chBtns) {
            chBtns.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
          }
          // Briefly flash the first chapter button to signal the launch
          const firstBtn = chBtns && chBtns.querySelector('.vocab-ch-btn');
          if (firstBtn) {
            firstBtn.style.boxShadow = `0 0 0 3px ${color}88`;
            setTimeout(() => { firstBtn.style.boxShadow = ''; }, 700);
          }
        }, 180);

        // 3. Visual feedback on the pill itself
        btn.style.background = color + '33';
        setTimeout(() => { btn.style.background = 'transparent'; }, 300);
      });
    });

    // Make the entire SRS row sticky so pills are always accessible
    const srsRow = srsWrap.closest('[style*="display:flex"]') || srsWrap.parentElement;
    if (srsRow && !srsRow.dataset.nzStickyApplied) {
      srsRow.dataset.nzStickyApplied = '1';
      srsRow.style.position   = 'sticky';
      srsRow.style.top        = '0';
      srsRow.style.zIndex     = '10';
      srsRow.style.background = 'var(--bg, #0f0f0f)';
      srsRow.style.paddingTop = '8px';
      srsRow.style.paddingBottom = '6px';
      srsRow.style.marginBottom  = '12px';
      srsRow.style.backdropFilter = 'blur(8px)';
    }
  }

  /* ── Bootstrap ────────────────────────────────────────────────────────── */

  function bootstrap() {
    // Wait for the vocab module's DOM to appear, then patch
    waitForEl('#vocab-srs-pills', 8000, () => {
      enhanceSRSPills();
      patchN5ChapterButtons();
    });

    // Also observe #vocab-level-tabs for level switches to re-apply labels
    waitForEl('#vocab-level-tabs', 8000, tabs => {
      tabs.addEventListener('click', () => {
        // Give the chapter buttons time to re-render then re-label
        setTimeout(patchN5ChapterButtons, 80);
        setTimeout(patchN5ChapterButtons, 300);
      });
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', bootstrap);
  } else {
    bootstrap();
  }
})();
